def main() -> int:
    cat = json.loads(EXHIBITORS.read_text(encoding="utf-8"))
    small = cat["cats"]["s"]
    by_key = {}
    for ex in cat["exhibitors"]:
        by_key[(ex["n"], ex["b"][0])] = ex
    facts_extra = json.loads(FACTS.read_text(encoding="utf-8")) if FACTS.exists() else {}

    sources = {"cat": {"label": "JIMTOF2026 公式オンラインカタログ（出展製品分類）", "url": CAT_URL}}
    for key, src in facts_extra.get("sources", {}).items():
        sources[key] = src

    items = []
    missing = []
    for it in ITEMS:
        companies = []
        seen = set()
        for name, booth, why, main_line in it["companies"]:
            ex = by_key.get((name, booth))
            if ex is None:
                missing.append(f"{name} {booth}")
                continue
            if (name, booth) in seen:
                raise SystemExit(f"同じ会社が2回：{name}")
            seen.add((name, booth))
            cats = [small[c[1:]]["t"] for c in ex.get("c", []) if c.startswith("s") and c[1:] in small]
            facts = [main_line]
            if cats:
                facts.append("出展製品分類（公式カタログ）：" + "・".join(cats[:6]) + ("…" if len(cats) > 6 else ""))
            src_ids = ["cat"]
            extra = facts_extra.get("companies", {}).get(f"{name}|{booth}")
            look = list(it["look"])
            if extra and extra.get("facts"):
                # JIMTOF2026 の出展内容が分かっている会社は、その要約を中心にする（分類の行は省く）
                facts = facts[:1] + extra["facts"]
                src_ids = extra.get("src", []) + src_ids
                specific = extra.get("look") or []
                look = (specific + [g for g in it["look"] if g not in specific])[:5]
            companies.append({
                "n": name,
                "b": booth,
                "why": why,
                "facts": facts,
                "look": look,
                "src": src_ids,
            })
        items.append({
            "id": it["id"],
            "mark": it["mark"],
            "short": it["short"],
            "title": it["title"],
            "preset": it["preset"],
            "intro": it["intro"],
            "guide": it["guide"],
            "companies": companies,
        })
    if missing:
        print("出展社データに無い：", missing, file=sys.stderr)
        return 1

    out = {
        "retrievedOn": facts_extra.get("retrievedOn", "2026-10-30"),
        "deadline": "2026-11-05",
        "note": "西展示棟担当（切削工具・保持具・測定機器）向けのおすすめです。社名・小間番号・出展製品分類は公式カタログの写し、"
                "「主力」は各社の一般的な製品分野、見どころは公開情報を確認できた会社だけに付けています",
        "sources": sources,
        "items": items,
    }
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: " + ", ".join(f"{i['id']}={len(i['companies'])}" for i in items))
    return 0


